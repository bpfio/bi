/**
 * BI-06.2 — 嵌入式原生快速搜索加速器（差异工单；与 BI-06.1 同属 sandbox 域资产）。
 *
 * buildSearchPrelude 生成一段 bash prelude 脚本（env 注入用）：定义透明劫持的
 * `find()` / `grep()` shell 函数——若预编译 bfs/ugrep 二进制可用（显式
 * BI_BFS_PATH / BI_UGREP_PATH 可执行，或 `command -v` 探测命中），参数逐字转发
 * 给原生二进制并自动追加 hidden/.git 排除过滤（各自语法）；不可用则走
 * `command find/grep` 透传执行真实 find/grep，语义零漂移。
 *
 * 版本兼容假设（declared）：
 * - bfs ≥ 1.14：`-nohidden` 与 `-exclude PATTERN` 为 bfs 专属选项；POSIX find
 *   没有对应物，因此 fallback 分支**不追加**任何过滤参数。
 * - ugrep ≥ 3.0：grep 兼容 CLI。`--hidden` 把 ugrep 的默认跳过隐藏文件行为
 *   恢复成 grep 语义；`--exclude-dir=.git` 排除 VCS 内部目录。
 *
 * 安全/设计声明：
 * - 函数体内不使用 `exec`：sourced 函数里的 exec 会替换整个宿主 shell 进程。
 *   透传用 `command`（绕过同名劫持函数），`return $?` 忠实回传退出码。
 * - 参数转发统一走 `eval` + `printf ' %q' "$@"`：%q 对每个参数重新引用后再
 *   求值，含空格/引号/glob 字符的参数逐字保真，且不会被 shell 二次展开。
 *   显式二进制路径同样经 %q 转发，路径含空格/引号也安全。
 * - 生成期的 export 行对路径做 POSIX 单引号转义；运行期路径经环境变量引用，
 *   两条通路互不干扰。
 * - fallback 分支不追加过滤参数：加速器只在劫持分支改变语义（少搜 .git 与
 *   隐藏文件），未注入 prelude 的环境完全不受影响。
 * - 劫持语义：prelude 之后的同 shell 调用 `find`/`grep` 走函数；用户显式写
 *   `command find` 或绝对路径可绕过劫持。
 *
 * detectSearchBinaries 为纯探测函数（零外部 npm 依赖）：注入 probe 优先；
 * 否则扫描候选目录列表；否则回退 PATH 环境变量。
 */

import { accessSync, constants as fsConstants, statSync } from "node:fs";
import { join } from "node:path";

// ---------------------------------------------------------------------------
// Public types
// ---------------------------------------------------------------------------

export interface SearchBinaries {
  bfs?: string;
  ugrep?: string;
}

export interface PreludeOptions {
  /** bfs 预编译二进制的显式路径（注入 BI_BFS_PATH；缺省靠 command -v 探测）。 */
  bfsPath?: string;
  /** ugrep 预编译二进制的显式路径（注入 BI_UGREP_PATH；缺省靠 command -v 探测）。 */
  ugrepPath?: string;
}

/** 注入式探测函数：给定工具名，返回可执行路径或 null。 */
export type SearchProbe = (name: "bfs" | "ugrep") => string | null;

// ---------------------------------------------------------------------------
// buildSearchPrelude
// ---------------------------------------------------------------------------

const PRELUDE_HEADER = `# BI-06.2 embedded-search prelude (generated by buildSearchPrelude; deterministic).
# Transparent find/grep accelerator for env injection:
#   - find()/grep() shell functions prefer a precompiled bfs/ugrep binary
#     (explicit BI_BFS_PATH / BI_UGREP_PATH, else discovered via command -v),
#     forwarding every argument verbatim via printf %q and appending
#     hidden/.git exclusion filters in each tool's own syntax.
#   - Otherwise the real find/grep runs unchanged (transparent fallback,
#     no filters appended).
# Version assumptions: bfs >= 1.14 (-nohidden/-exclude), ugrep >= 3.0
# (grep-compatible CLI; --hidden restores grep hidden semantics).
# NOTE: no exec inside functions — a sourced function calling exec would
# replace the host shell; \`command\` bypasses the hijacking functions.`;

const PRELUDE_FUNCTIONS = `__bi_search_have() { command -v "$1" >/dev/null 2>&1; }

find() {
  if [ -n "$BI_BFS_PATH" ] && [ -x "$BI_BFS_PATH" ]; then
    eval "$(printf ' %q' "$BI_BFS_PATH") -nohidden -exclude .git$(printf ' %q' "$@")"
    return $?
  fi
  if __bi_search_have bfs; then
    eval "command bfs -nohidden -exclude .git$(printf ' %q' "$@")"
    return $?
  fi
  command find "$@"
}

grep() {
  if [ -n "$BI_UGREP_PATH" ] && [ -x "$BI_UGREP_PATH" ]; then
    eval "$(printf ' %q' "$BI_UGREP_PATH") --hidden --exclude-dir=.git$(printf ' %q' "$@")"
    return $?
  fi
  if __bi_search_have ugrep; then
    eval "command ugrep --hidden --exclude-dir=.git$(printf ' %q' "$@")"
    return $?
  fi
  command grep "$@"
}`;

/** POSIX 单引号转义（' → '\''）。 */
function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * 生成 bash prelude：头部说明 +（可选）显式二进制 export 行 + find()/grep()
 * 劫持函数。同一输入字节级确定（无时间戳、无随机序）。
 */
export function buildSearchPrelude(opts: PreludeOptions = {}): string {
  const parts: string[] = [PRELUDE_HEADER];
  if (opts.bfsPath !== undefined) {
    parts.push(`export BI_BFS_PATH=${shQuote(opts.bfsPath)}`);
  }
  if (opts.ugrepPath !== undefined) {
    parts.push(`export BI_UGREP_PATH=${shQuote(opts.ugrepPath)}`);
  }
  parts.push(PRELUDE_FUNCTIONS);
  return `${parts.join("\n")}\n`;
}

// ---------------------------------------------------------------------------
// detectSearchBinaries
// ---------------------------------------------------------------------------

/**
 * 探测 bfs / ugrep 可执行文件。优先级：注入 probe > 候选目录列表 > PATH。
 * 找不到的工具在结果中缺省（不出现在返回对象里）。
 */
export function detectSearchBinaries(paths?: string[], probe?: SearchProbe): SearchBinaries {
  const result: SearchBinaries = {};
  const bfs = resolveBinary("bfs", paths, probe);
  if (bfs !== null) result.bfs = bfs;
  const ugrep = resolveBinary("ugrep", paths, probe);
  if (ugrep !== null) result.ugrep = ugrep;
  return result;
}

function resolveBinary(
  name: "bfs" | "ugrep",
  paths: string[] | undefined,
  probe: SearchProbe | undefined,
): string | null {
  if (probe !== undefined) return probe(name);
  const dirs = paths ?? defaultPathDirs();
  return findExecutableIn(dirs, name);
}

function defaultPathDirs(): string[] {
  return (process.env.PATH ?? "").split(":").filter((dir) => dir.length > 0);
}

function findExecutableIn(dirs: string[], name: string): string | null {
  for (const dir of dirs) {
    const candidate = join(dir, name);
    if (isExecutableFile(candidate)) return candidate;
  }
  return null;
}

function isExecutableFile(path: string): boolean {
  try {
    if (!statSync(path).isFile()) return false;
    accessSync(path, fsConstants.X_OK);
    return true;
  } catch {
    return false;
  }
}
